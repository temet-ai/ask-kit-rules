export const meta = {
  purpose:
    "Every instruction file that loads, or may load, for a folder, in load order, with its scope (managed, user, parent, project, nested, memory, generated), when it loads (launch, on-demand, no), lines, bytes, estimated tokens (bytes/4) and rule items, plus totals per scope, the tokens that load at launch, the memory folder, and warnings (a file over 200 lines, MEMORY.md over its limit, an on-demand file over its character limit). Use it for what a session in this folder is told and how big that is.",
  params: {
    folder: "the folder to resolve for, optional (default: the folder the caller works in)",
    topics: "list every memory topic file, default false (they are summed in one line)",
    launchOnly: "list only what loads at launch, default false",
    nested: "include CLAUDE.md, AGENTS.md and rules in subfolders, default true",
  },
  returns: "{folder, instructionFiles, agentsMdRead, files:['<order> <scope> <loads> <path> | <lines> lines, <tokens> tokens, <items> items | flags'], totals:{scope:{files,items,lines,bytes,tokens}}, launch:{files, tokens}, memory:{dir, exists}, notes, warnings}; one line per file, in load order",
  example: 'await scripts.run("loaded", { folder: "/path/to/my-app" })',
};

export default async function ({ rules }, { folder, topics = false, launchOnly = false, nested = true } = {}) {
  const r = await rules.loaded(folder, { topics, launchOnly, nested });
  const home = process.env.HOME || "";
  const short = (p) => (home && p.startsWith(home + "/") ? "~" + p.slice(home.length) : p);
  const files = r.files.map((f) => {
    const flags = [];
    if (f.generated) flags.push("generated by mike: change it in mike");
    if (f.paths) flags.push("paths: " + f.paths.join(", ").slice(0, 80));
    if (f.files) flags.push(f.files + " files");
    if (f.truncated) flags.push("over its launch limit");
    if (f.sameContentAs) flags.push("same content as " + short(f.sameContentAs));
    if (f.importedBy) flags.push("imported by " + short(f.importedBy));
    if (f.note && !f.paths && !f.truncated) flags.push(f.note);
    return `${f.order ?? "-"} ${f.scope} ${f.loads} ${short(f.path)} | ${f.lines ?? "?"} lines, ${f.tokens} tokens, ${f.items ?? "?"} items${flags.length ? " | " + flags.join("; ") : ""}`;
  });
  return { ...r, files };
}
